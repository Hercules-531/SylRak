import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
const base='http://127.0.0.1:8010';
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:900}});
const page=await context.newPage();const errors=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));
const get=async p=>(await context.request.get(base+'/api/v1'+p)).json();
const malformed=/[\u00c2\u00c3\ufffd]|\u00e2[\u20ac\u2020]/;
await mkdir('artifacts/qa/polish',{recursive:true});
try{
 await page.goto(base);await page.getByRole('heading',{name:'City command',exact:true}).waitFor();
 await page.mouse.move(600,180);
 await page.locator('.camera-pin').first().waitFor();
 await page.evaluate(()=>document.fonts.ready);
 assert.equal(await page.evaluate(()=>getComputedStyle(document.body).backgroundColor),'rgb(0, 0, 0)');
 assert.equal(await page.getByLabel('Open navigation').getAttribute('aria-expanded'),'false');
 const before=await page.locator('.main-shell').boundingBox();
 await page.getByLabel('Open navigation').hover();
 await page.waitForFunction(()=>Math.abs(document.querySelector('.sidebar').getBoundingClientRect().left-24)<.5);
 assert.equal((await page.locator('.main-shell').boundingBox()).x,before.x);
 await page.screenshot({path:'artifacts/qa/polish/navigation-open-1440.png'});
 await page.mouse.move(600,180);
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('.sidebar')).visibility==='hidden');
 await page.getByLabel('Open navigation').focus();
 await page.waitForFunction(()=>document.querySelector('.navigation-trigger').getAttribute('aria-expanded')==='true');
 await page.keyboard.press('Escape');
 await page.waitForFunction(()=>document.querySelector('.navigation-trigger').getAttribute('aria-expanded')==='false');
 await page.locator('.global-search input').click();
 assert.ok((await page.locator('.command-today').innerText()).includes(await page.evaluate(()=>new Intl.DateTimeFormat('en-IN',{timeZone:'Asia/Kolkata',day:'2-digit',month:'short',year:'numeric'}).format(new Date()))));
 assert.ok(!malformed.test(await page.locator('body').innerText()));
 await page.screenshot({path:'artifacts/qa/polish/command-1440.png'});
 checks.push('OLED background, current IST date, repaired symbols, hover/focus/Escape navigation without map shift');
 const usage=await get('/jev/status');
 await page.goto(base+'/appearance');await page.locator('.jev-assistant summary').click();
 await page.getByLabel('Jev vehicle description').fill('A white Creta with a black roof, a red door panel and a roof rack');
 await page.getByRole('button',{name:'Search with Jev',exact:true}).click();
 await page.getByText('Search complete using saved Jev filters · results below',{exact:true}).waitFor();
 await page.locator('.candidate-card').first().waitFor();
 assert.ok((await page.locator('.candidate-card').first().innerText()).includes('DL4CAB6672'));
 assert.equal(await page.getByLabel('Appearance model').inputValue(),'Hyundai Creta');
 assert.equal((await get('/jev/status')).requests,usage.requests);
 assert.equal(await page.getByRole('button',{name:'Apply suggestions to filters'}).count(),0);
 await page.locator('.candidate-card .review-assessment summary').first().click();
 assert.ok((await page.locator('.review-warning').first().innerText()).includes('may be inaccurate'));
 await page.locator('#appearance-results').scrollIntoViewIfNeeded();
 await page.screenshot({path:'artifacts/qa/polish/appearance-1440.png'});
 checks.push('One-click cached Jev classification applies filters and displays ranked results; no additional online request');
 await page.goto(base+'/investigations?q=DL8CAF2041');
 await page.getByRole('columnheader',{name:'Experimental review',exact:true}).waitFor();
 await page.locator('.data-table .review-assessment summary').first().click();
 await page.locator('.plate-link').first().click();
 await page.locator('.vehicle-review .review-assessment summary').click();
 assert.ok((await page.locator('.vehicle-review').innerText()).includes('not a probability'));
 checks.push('Plate results and vehicle history show separate, explainable experimental review scores');
 for(const width of [1440,1366,390]){
  await page.setViewportSize({width,height:width===390?844:width===1366?768:900});
  await page.goto(base);await page.getByRole('heading',{name:'City command',exact:true}).waitFor();
  await page.locator('.camera-pin').first().waitFor();await page.waitForTimeout(250);
  await page.mouse.move(width-30,180);await page.evaluate(()=>window.scrollTo(0,0));
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Overflow at ${width}`);
  assert.ok(!malformed.test(await page.locator('body').innerText()));
  await page.screenshot({path:`artifacts/qa/polish/command-${width}.png`});
 }
 await page.getByLabel('Open navigation').click();
 await page.getByRole('link',{name:'Investigations',exact:true}).click();
 await page.getByRole('heading',{name:'Find a vehicle. Reconstruct its history.'}).waitFor();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 checks.push('1440px, 1366px and 390px layouts fit; narrow-screen navigation works');
 assert.deepEqual(errors,[]);
 await writeFile('artifacts/qa/polish/results.json',JSON.stringify({checks,errors},null,2));
 console.log(JSON.stringify({checks,errors}));
}catch(e){await page.screenshot({path:'artifacts/qa/polish/failure.png',fullPage:true});throw e}finally{await browser.close()}
