import {chromium} from 'playwright';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const base=process.argv[2]||'http://127.0.0.1:8010';
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:900}});
const errors=[],external=[],checks=[];
await context.route('**/*',r=>{const u=new URL(r.request().url());if(['http:','https:'].includes(u.protocol)&&!['127.0.0.1','localhost'].includes(u.hostname)){external.push(u.href);return r.abort()}return r.continue()});
const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.status()>=500)errors.push(r.status()+' '+r.url())});
const get=async p=>(await context.request.get(base+'/api/v1'+p)).json();
const post=async(p,data)=>{const r=await context.request.post(base+'/api/v1'+p,{data});assert.ok(r.ok(),await r.text());return r.json()};
try{
 const before=await get('/snapshot');
 await page.goto(base+'/registrations');
 await page.getByRole('button',{name:'DL10CZ7788',exact:true}).click();
 await page.getByText('Demonstration registration record',{exact:true}).waitFor();
 assert.equal((await get('/snapshot')).summary.passages,before.summary.passages);
 await page.screenshot({path:'artifacts/qa/registration-1440.png',fullPage:true});
 await page.getByLabel('Registration lookup number').fill('DL99ZZ9999');
 await page.getByRole('button',{name:'Look up registration'}).click();
 await page.getByText('No demonstration record is available. Live registration lookup is not connected.').waitFor();
 checks.push('Independent registration lookup returns labeled records and honest unavailable state without ingesting sightings');
 await page.goto(base+'/alerts');
 const all=await get('/alerts');assert.ok(all.length);const a=all[0];
 await page.getByLabel('Vehicle alert controls').first().selectOption('mute:15');
 await page.getByText('Notification preference saved',{exact:true}).waitFor();
 await page.getByLabel('Alert state filter').selectOption('muted');
 await page.getByLabel('Vehicle alert controls').first().waitFor();
 assert.ok((await get('/alerts?status=muted')).some(x=>x.id===a.id));
 await page.screenshot({path:'artifacts/qa/muted-alert.png',fullPage:true});
 await page.getByLabel('Vehicle alert controls').first().selectOption('unmute');
 await page.getByLabel('Alert state filter').selectOption('');
 await page.getByLabel('Vehicle alert controls').first().waitFor();
 checks.push('Per-vehicle mute, Muted filter, and unmute work through visible controls');
 await page.goto(base+'/appearance');
 await page.getByRole('button',{name:'Multicolor car',exact:true}).click();
 await page.locator('.candidate-card').first().waitFor();
 const multicolor=await post('/search/candidates',{colors:['white','black'],pattern:'contrasting panel',include_unknown:false});
 assert.equal(multicolor.items[0].observation.plate,'DL4CAB6672');assert.equal(multicolor.items[0].sightings,4);
 await page.getByRole('link',{name:'History (4)'}).first().click();
 await page.locator('.camera-pin').first().waitFor();
 await page.getByText('DL4CAB6672',{exact:true}).first().waitFor();
 checks.push('Multicolor description search opens four-camera vehicle history');
 await page.goto(base+'/appearance');await page.getByRole('button',{name:'White Dzires',exact:true}).click();
 await page.locator('.candidate-card').first().waitFor();
 const boxes=page.locator('.candidate-select input');await boxes.nth(0).check();await boxes.nth(1).check();
 await page.getByRole('button',{name:'Compare selected (2)'}).click();
 await page.getByRole('heading',{name:'Compare visible evidence'}).waitFor();
 await page.screenshot({path:'artifacts/qa/candidate-comparison.png',fullPage:true});
 await page.getByRole('button',{name:'Close',exact:true}).click();
 await page.getByLabel('Case title').fill('White Dzire — demonstration review');
 await page.getByRole('button',{name:'Add 2 candidates',exact:true}).click();
 await page.getByRole('heading',{name:'White Dzire — demonstration review'}).waitFor();
 await page.getByRole('button',{name:'Accept case connection'}).first().click();
 await page.getByLabel('Case review reason').fill('Operator comparison for demonstration; identity remains a case hypothesis.');
 await page.getByRole('button',{name:'Save accepted decision'}).click();
 await page.getByRole('button',{name:'Journey',exact:true}).click();
 await page.getByRole('heading',{name:'Operator-accepted case sightings'}).waitFor();
 await page.locator('.camera-pin').first().waitFor();
 await page.screenshot({path:'artifacts/qa/case-journey-1440.png',fullPage:true});
 await page.getByLabel('Show proposed connections').check();
 await page.getByRole('heading',{name:'Proposed connections'}).waitFor();
 await page.setViewportSize({width:1366,height:768});await page.waitForTimeout(700);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
 await page.screenshot({path:'artifacts/qa/case-journey-1366.png',fullPage:true});
 checks.push('Ambiguous candidates compare without merging, case review and separate journey layers work at both desktop sizes');
 await page.goto(base+'/appearance');await page.getByRole('button',{name:'Covered vehicles',exact:true}).click();
 await page.locator('.candidate-card').first().waitFor();
 await page.screenshot({path:'artifacts/qa/covered-candidates.png',fullPage:true});
 checks.push('Covered-vehicle scenario remains uncertain with no fabricated photographic evidence');
 assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
 await writeFile('artifacts/qa/upgrade-browser-results.json',JSON.stringify({checks,errors,external_requests:external},null,2));
 console.log(JSON.stringify({checks,errors,external_requests:external}));
}catch(e){await page.screenshot({path:'artifacts/qa/upgrade-failure.png',fullPage:true});console.error(e);console.error(errors);process.exitCode=1}finally{await browser.close()}
